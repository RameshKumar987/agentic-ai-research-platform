import type { Project } from "./types";
import { formatDateTime, generatorLabel, slugify } from "./format";

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function projectToMarkdown(project: Project): string {
  const lines: string[] = [
    `# ${project.title}`,
    "",
    `> Generated with ResearchHub. ${project.meta.notes[0] ?? ""}`,
    "",
    `- **Project ID:** ${project.id}`,
    `- **Domain:** ${project.domain}`,
    `- **Complexity:** ${project.complexity}`,
    `- **Generated:** ${formatDateTime(project.meta.generatedAt)}`,
    `- **Blueprint engine:** ${generatorLabel(project.meta.generator)}`,
    `- **Agent execution:** not performed (simulated design only)`,
    "",
    "## Summary",
    "",
    project.summary,
    "",
  ];

  project.sections.forEach((section, index) => {
    lines.push(`## ${index + 1}. ${section.title}`, "");
    section.content.forEach((paragraph) => {
      lines.push(paragraph, "");
    });
  });

  lines.push("## Suggested Technology Stack", "");
  lines.push("| Technology | Category | Purpose | Status |", "| --- | --- | --- | --- |");
  project.techStack.forEach((item) => {
    lines.push(
      `| ${escapeCell(item.name)} | ${escapeCell(item.category)} | ${escapeCell(item.purpose)} | ${item.status} |`,
    );
  });
  lines.push("");

  lines.push("## Suggested API Endpoints", "", "> Design proposal only. None are implemented by this MVP.", "");
  lines.push("| Method | Path | Purpose | Auth |", "| --- | --- | --- | --- |");
  project.apiEndpoints.forEach((endpoint) => {
    lines.push(
      `| ${endpoint.method} | \`${escapeCell(endpoint.path)}\` | ${escapeCell(endpoint.purpose)} | ${escapeCell(endpoint.auth)} |`,
    );
  });
  lines.push("");

  lines.push("## Database Entities", "");
  project.databaseEntities.forEach((entity) => {
    lines.push(`### ${entity.name}`, "", entity.purpose, "");
    lines.push("| Field | Type | Notes |", "| --- | --- | --- |");
    entity.fields.forEach((field) => {
      lines.push(`| \`${field.name}\` | ${escapeCell(field.type)} | ${escapeCell(field.notes)} |`);
    });
    if (entity.relationships.length > 0) {
      lines.push("", `**Relationships:** ${entity.relationships.join("; ")}`);
    }
    lines.push("");
  });

  lines.push("## Risks and Limitations", "");
  project.risks.forEach((risk) => {
    lines.push(`### ${risk.title}`, "", `- **Impact:** ${risk.impact}`, `- **Mitigation:** ${risk.mitigation}`, "");
  });

  lines.push("## Next Steps", "");
  project.nextSteps.forEach((step, index) => {
    lines.push(`${index + 1}. ${step}`);
  });
  lines.push("");

  lines.push("## Proposed Architecture", "");
  lines.push(project.architecture.implementedSummary, "");
  lines.push(project.architecture.proposedSummary, "");
  lines.push("```mermaid", project.architecture.mermaid.trim(), "```", "");

  lines.push("---", "");
  lines.push(
    "Generated by ResearchHub MVP. This blueprint is deterministic template output. It is not the result of web research, LLM agents, RAG retrieval, or production architecture verification.",
    "",
  );

  return lines.join("\n");
}

export function downloadMarkdown(project: Project): void {
  const markdown = projectToMarkdown(project);
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `${slugify(project.title)}.md`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function fallbackCopy(text: string): boolean {
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.select();
  let copied = false;
  try {
    copied = document.execCommand("copy");
  } catch {
    copied = false;
  }
  textarea.remove();
  return copied;
}

export async function copyText(text: string): Promise<void> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return;
    }
  } catch {
    // Fall through to the legacy path when permissions are denied.
  }

  if (!fallbackCopy(text)) {
    throw new Error("Clipboard access is blocked. Select the report text manually or download Markdown.");
  }
}
